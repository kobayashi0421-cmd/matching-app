export const TIER_COUNT = 5;

/** 各段階(1〜5)から1問ずつ選ぶ。前回と同じ問題はなるべく避ける */
export function pickPuzzleIds(prev?: number[]): number[] {
  return Array.from({ length: TIER_COUNT }, (_, i) => {
    const all = PUZZLE_POOL.filter((p) => p.tier === i + 1);
    const fresh = all.filter((p) => p.id !== prev?.[i]);
    const list = fresh.length > 0 ? fresh : all;
    return list[Math.floor(Math.random() * list.length)].id;
  });
}

/** 第 question 問(1〜5)の問題。ids が無いとき(古いルームなど)は各段階の先頭の問題 */
export function getPuzzle(ids: number[] | undefined, question: number): Puzzle {
  const tier = Math.min(Math.max(question, 1), TIER_COUNT);
  const id = ids?.[tier - 1];
  return PUZZLE_POOL.find((p) => p.id === id) ?? PUZZLE_POOL.find((p) => p.tier === tier)!;
}
